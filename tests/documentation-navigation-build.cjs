const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const {test} = require('node:test');

test('applied proposal orders index, generated sidebar and both paginator directions', {timeout: 330000}, () => {
  const root = path.resolve(__dirname, '..');
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'navigation-build-'));
  const repository = path.join(fixture, 'repository with spaces');
  const registration = 'registrarte-probar-beesible-y-activar-el-plan-start';
  const access = 'acceder-a-la-plataforma';
  try {
    const prepared = spawnSync('python', ['-B', path.join(root, '.github/scripts/tests/navigation_fixture.py'),
      repository, path.join(fixture, 'report.json')], {cwd: root, encoding: 'utf8'});
    assert.equal(prepared.status, 0, `${prepared.stdout}\n${prepared.stderr}`);
    const config = path.join(fixture, 'docusaurus.config.cjs');
    const output = path.join(fixture, 'build');
    const sidebar = path.join(fixture, 'sidebars.cjs');
    fs.writeFileSync(sidebar, "module.exports = {docsSidebar: [{type: 'autogenerated', dirName: 'centro-de-ayuda'}]};\n");
    fs.writeFileSync(config, `module.exports = ${JSON.stringify({
      title: 'Navegación de prueba', url: 'https://example.invalid', baseUrl: '/documentation-poc/',
      trailingSlash: true, onBrokenLinks: 'throw',
      presets: [[require.resolve('@docusaurus/preset-classic'), {docs: {
        path: path.join(repository, 'docs'), routeBasePath: '/', sidebarPath: sidebar,
      }, blog: false}]],
    })};\n`);
    const build = spawnSync(process.execPath, [require.resolve('@docusaurus/core/bin/docusaurus.mjs'),
      'build', root, '--config', config, '--out-dir', output, '--no-minify'],
    {cwd: root, encoding: 'utf8', timeout: 300000, env: {...process.env, CI: 'true', NO_COLOR: '1'}});
    assert.equal(build.status, 0, `${build.error || ''}\n${build.stdout}\n${build.stderr}`);
    const category = path.join(output, 'centro-de-ayuda/inicio-y-acceso');
    const index = fs.readFileSync(path.join(category, 'index.html'), 'utf8');
    const article = index.match(/<article\b[\s\S]*?<\/article>/)[0];
    assert.ok(article.indexOf(registration) < article.indexOf(access), 'Index must put registration first');
    const nav = index.match(/<nav\b[^>]*class="[^"]*menu[^\"]*"[\s\S]*?<\/nav>/)[0];
    assert.ok(nav.indexOf(registration) < nav.indexOf(access), 'Autogenerated sidebar must put registration first');
    const registered = fs.readFileSync(path.join(category, registration, 'index.html'), 'utf8');
    const accessed = fs.readFileSync(path.join(category, access, 'index.html'), 'utf8');
    assert.match(registered, new RegExp(`aria-label="Ir al artículo siguiente: Acceder a la plataforma"[^>]*href="[^"]*${access}`));
    assert.match(accessed, new RegExp(`aria-label="Ir al artículo anterior: Registrarte, probar Beesible y activar el Plan Start"[^>]*href="[^"]*${registration}`));
    assert.ok(registered.includes('Plan Start'));
  } finally {
    assert.equal(path.dirname(fixture), os.tmpdir());
    fs.rmSync(fixture, {recursive: true, force: true});
  }
});
